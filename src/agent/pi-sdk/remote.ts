import { closeSync, existsSync, mkdirSync, openSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { execFileSync, type ChildProcess } from 'node:child_process';
import { log } from '../../core/logger';
import { spawnProcess } from '../../platform/spawn';
import { terminateChild } from '../../platform/terminate';

/**
 * Remote execution for the shared Pi SDK host.
 *
 * The host protocol is newline-delimited JSON over stdin/stdout, so an ssh
 * channel carries it unchanged: only the command line and the environment
 * delivery differ. The host runs on a node that mounts the same shared
 * filesystem, so `nodePath`, `hostScript`, the SDK entry and `agentDir` keep
 * their absolute paths.
 *
 * Per-run bindings (workflow credentials) travel in an environment file next to
 * the profile state rather than on the remote command line, so they never show
 * up in the remote `ps`.
 */

export interface PiRemoteTarget {
  /** ssh destination: `host` or `user@host`. */
  destination: string;
  /** ssh binary; tests point this at a stand-in. */
  ssh?: string;
  /** Extra ssh options, appended before the destination. */
  sshOptions?: readonly string[];
  /** Must be readable from the remote node (shared filesystem). */
  stateDir: string;
}

/** Transport-level flags every remote host and tunnel carries. */
const SSH_BASE_OPTIONS = [
  '-o', 'BatchMode=yes',
  '-o', 'ServerAliveInterval=15',
  '-o', 'ServerAliveCountMax=3',
];

export function shellQuote(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`;
}

const ENV_NAME = /^[A-Za-z_][A-Za-z0-9_]*$/;

export interface RemoteEnvFile {
  path: string;
  cleanup(): void;
}

// Node's POSIX mode does not set an NTFS DACL. Protect the new, empty file before writing any values.
function writePrivateFile(path: string, text: string): void {
  const fd = openSync(path, 'wx', 0o600);
  let written = false;
  try {
    if (process.platform === 'win32') {
      const system = join(process.env.SystemRoot || 'C:\\Windows', 'System32');
      const powershell = join(system, 'WindowsPowerShell', 'v1.0', 'powershell.exe');
      const protectFile = [
        "$ErrorActionPreference = 'Stop'",
        '$sid = [System.Security.Principal.WindowsIdentity]::GetCurrent().User',
        '$rights = [System.Security.AccessControl.FileSystemRights]::FullControl',
        '$allow = [System.Security.AccessControl.AccessControlType]::Allow',
        '$acl = [System.Security.AccessControl.FileSecurity]::new()',
        '$acl.SetAccessRuleProtection($true, $false)',
        '$acl.AddAccessRule([System.Security.AccessControl.FileSystemAccessRule]::new($sid, $rights, $allow))',
        '[IO.File]::SetAccessControl($env:BRIDGE_PRIVATE_ENV_FILE, $acl)',
        '$actual = [IO.File]::GetAccessControl($env:BRIDGE_PRIVATE_ENV_FILE)',
        '$rules = $actual.GetAccessRules($true, $true, [System.Security.Principal.SecurityIdentifier])',
        'if (!$actual.AreAccessRulesProtected -or $rules.Count -ne 1 -or $rules[0].IdentityReference -ne $sid' +
          " -or $rules[0].AccessControlType -ne $allow -or $rules[0].FileSystemRights -ne $rights) { throw 'Private file access check failed' }",
      ].join('; ');
      execFileSync(powershell, ['-NoProfile', '-NonInteractive', '-Command', protectFile], {
        env: { ...process.env, BRIDGE_PRIVATE_ENV_FILE: path }, windowsHide: true,
      });
    }
    writeFileSync(fd, text);
    written = true;
  } finally {
    closeSync(fd);
    if (!written) rmSync(path, { force: true });
  }
}

/**
 * Write the host environment where both machines can read it. Values keep
 * exact bytes (quoted for the shell); the file is private to the bridge user.
 */
function writeRemoteEnvFile(stateDir: string, env: NodeJS.ProcessEnv, tag = 'host'): RemoteEnvFile {
  const dir = join(stateDir, 'remote-env');
  mkdirSync(dir, { recursive: true, mode: 0o700 });
  const path = join(dir, `${tag}-${process.pid}-${Date.now()}-${Math.random().toString(36).slice(2, 8)}.sh`);
  const lines = ['# generated by lark-channel-bridge; removed when the run ends'];
  for (const [name, value] of Object.entries(env)) {
    if (value === undefined || !ENV_NAME.test(name)) continue;
    lines.push(`export ${name}=${shellQuote(value)}`);
  }
  writePrivateFile(path, lines.join('\n') + '\n');
  return {
    path,
    cleanup: () => {
      try {
        rmSync(path, { force: true });
      } catch (error) {
        log.warn('agent', 'pi-sdk-remote-env-cleanup-failed', { path, error: String(error) });
      }
    },
  };
}

export interface RemoteHostSpawn {
  command: string;
  args: string[];
  envFile: string;
  cleanup(): void;
}

/**
 * Wrap the host command line in an ssh invocation. The remote shell sources the
 * environment file, then execs the host so signals reach it directly.
 */
export function remoteHostSpawn(
  target: PiRemoteTarget,
  input: {
    nodePath: string;
    hostScript: string;
    args: readonly string[];
    cwd?: string;
    env: NodeJS.ProcessEnv;
  },
): RemoteHostSpawn {
  if (!target.destination || target.destination.startsWith('-') || /\s/.test(target.destination)) {
    throw new Error(`pi.remote: invalid ssh destination ${JSON.stringify(target.destination)}`);
  }
  const envFile = writeRemoteEnvFile(target.stateDir, input.env);
  const script = [
    'set -eu',
    `. ${shellQuote(envFile.path)}`,
    // The values are in the host's environment now; both machines share the
    // filesystem, so the file does not have to outlive this line.
    `rm -f ${shellQuote(envFile.path)}`,
    ...(input.cwd ? [`cd ${shellQuote(input.cwd)}`] : []),
    `exec ${[input.nodePath, input.hostScript, ...input.args].map(shellQuote).join(' ')}`,
  ].join('; ');
  return {
    command: target.ssh ?? 'ssh',
    args: [...SSH_BASE_OPTIONS, ...(target.sshOptions ?? []), target.destination, script],
    envFile: envFile.path,
    cleanup: envFile.cleanup,
  };
}

export interface WorkflowTunnel {
  /** Endpoint the remote host must use for `AGENT_WORKFLOW_ENDPOINT`. */
  endpoint: string;
  close(): Promise<void>;
}

const REMOTE_PORT_MIN = 20_000;
const REMOTE_PORT_SPAN = 40_000;
const TUNNEL_READY_MS = 500;
const TUNNEL_ATTEMPTS = 5;

function tunnelPort(localEndpoint: string): number {
  const url = new URL(localEndpoint);
  if (url.protocol !== 'http:' || url.hostname !== '127.0.0.1') {
    throw new Error(`workflow endpoint is not a local http endpoint: ${localEndpoint}`);
  }
  const port = Number(url.port);
  if (!Number.isSafeInteger(port) || port <= 0) throw new Error(`workflow endpoint has no port: ${localEndpoint}`);
  return port;
}

/**
 * Publish the bridge's local-only workflow endpoint on the remote loopback.
 * `ExitOnForwardFailure` turns a busy remote port into an immediate exit, so a
 * dead tunnel is never mistaken for a working one.
 */
export async function openWorkflowTunnel(
  target: PiRemoteTarget,
  localEndpoint: string,
  options: { attempts?: number; readyMs?: number } = {},
): Promise<WorkflowTunnel> {
  const localPort = tunnelPort(localEndpoint);
  const attempts = options.attempts ?? TUNNEL_ATTEMPTS;
  const readyMs = options.readyMs ?? TUNNEL_READY_MS;
  let lastError = 'no remote port available';
  for (let attempt = 0; attempt < attempts; attempt += 1) {
    const remotePort = REMOTE_PORT_MIN + ((Date.now() + attempt * 7919) % REMOTE_PORT_SPAN);
    const child = spawnProcess(target.ssh ?? 'ssh', [
      '-N', '-T',
      '-o', 'ExitOnForwardFailure=yes',
      ...SSH_BASE_OPTIONS,
      ...(target.sshOptions ?? []),
      '-R', `127.0.0.1:${remotePort}:127.0.0.1:${localPort}`,
      target.destination,
    ], { stdio: ['ignore', 'ignore', 'pipe'] });
    let stderr = '';
    child.stderr?.on('data', (chunk: Buffer) => { stderr += chunk.toString('utf8'); });
    const failed = await tunnelReadiness(child, readyMs);
    if (failed === undefined) {
      log.info('agent', 'pi-sdk-tunnel-open', { remotePort, localPort, destination: target.destination });
      return {
        endpoint: `http://127.0.0.1:${remotePort}/workflow`,
        close: async () => {
          terminateChild(child, 'SIGTERM');
          log.info('agent', 'pi-sdk-tunnel-close', { remotePort });
        },
      };
    }
    lastError = failed || stderr.trim() || `ssh exited with code ${String(child.exitCode)}`;
  }
  throw new Error(`cannot publish the workflow endpoint on ${target.destination}: ${lastError}`);
}

/** Resolves to a failure reason when the tunnel died while starting, undefined when it is up. */
function tunnelReadiness(child: ChildProcess, readyMs: number): Promise<string | undefined> {
  return new Promise((resolve) => {
    let settled = false;
    const finish = (reason: string | undefined) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      child.removeListener('exit', onExit);
      child.removeListener('error', onError);
      resolve(reason);
    };
    const timer = setTimeout(() => finish(undefined), readyMs);
    timer.unref?.();
    const onExit = (code: number | null, signal: NodeJS.Signals | null) =>
      finish(`ssh exited while starting the tunnel (code=${String(code)}, signal=${String(signal)})`);
    const onError = (error: Error) => finish(error.message);
    child.once('exit', onExit);
    child.once('error', onError);
  });
}

/**
 * The endpoint a run was given, whether it came inline or through the published
 * file. The file names a port on the bridge machine, so a remote host can only
 * use it after this process reads it.
 */
export function localWorkflowEndpoint(env: Readonly<Record<string, string>>): string | undefined {
  if (env.AGENT_WORKFLOW_ENDPOINT) return env.AGENT_WORKFLOW_ENDPOINT;
  const file = env.AGENT_WORKFLOW_ENDPOINT_FILE;
  if (!file) return undefined;
  try {
    const parsed = JSON.parse(readFileSync(file, 'utf8')) as { endpoint?: unknown };
    return typeof parsed.endpoint === 'string' ? parsed.endpoint : undefined;
  } catch (error) {
    log.warn('agent', 'pi-sdk-remote-endpoint-file-unreadable', { file, error: String(error) });
    return undefined;
  }
}

/** Rewrite a run environment for a remote host: the endpoint becomes the tunnel and the local-only file goes away. */
export function remoteRunEnv(env: Readonly<Record<string, string>>, endpoint: string): Record<string, string> {
  const { AGENT_WORKFLOW_ENDPOINT_FILE: _file, ...rest } = withoutLocalScratch(env);
  return { ...rest, AGENT_WORKFLOW_ENDPOINT: endpoint };
}

/**
 * A workflow worker's scratch directory is on the bridge machine. On another machine the path does not exist, and a
 * TMPDIR that names it breaks every tool that makes a temporary file, so the worker keeps that machine's own.
 */
export function withoutLocalScratch(env: Readonly<Record<string, string>>): Record<string, string> {
  const { AGENT_WORKFLOW_SCRATCH: scratch, ...rest } = env;
  if (scratch === undefined) return rest;
  return Object.fromEntries(Object.entries(rest).filter(([name, value]) => !(['TMPDIR', 'TMP', 'TEMP'].includes(name) && value === scratch)));
}

/** Sweep environment files whose host died before it could clean up. */
export function sweepRemoteEnvFiles(stateDir: string, maxAgeMs = 24 * 60 * 60_000): void {
  const dir = join(stateDir, 'remote-env');
  if (!existsSync(dir)) return;
  const now = Date.now();
  try {
    for (const name of readdirSync(dir)) {
      const path = join(dir, name);
      try {
        if (now - statSync(path).mtimeMs > maxAgeMs) rmSync(path, { force: true });
      } catch {
        // Another bridge may have removed it already.
      }
    }
  } catch (error) {
    log.warn('agent', 'pi-sdk-remote-env-sweep-failed', { dir, error: String(error) });
  }
}
